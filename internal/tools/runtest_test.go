func TestRunTestReportsFailureAndTimeoutWithoutSuccess(t *testing.T) {
	requireSandboxHost(t)
	failing, _, _ := writeProbeProject(t, `package probe
import "testing"
func TestFail(t *testing.T) { t.Fatal("intentional failure") }
`)
	result, err := RunTest(context.Background(), failing, RunTestInput{Toolchain: "go"})
	if err != nil {
		t.Fatal(err)
	}
	if result.Passed || result.ExitCode == 0 || !strings.Contains(result.Output, "intentional failure") {
		t.Fatalf("failing test was not reported honestly: %+v\n%s", result, result.Output)
	}

	slow := writeSlowNPMProject(t)
	started := time.Now()
	timed, err := RunTest(context.Background(), slow, RunTestInput{Toolchain: "npm", TimeoutSeconds: 5})
	if err != nil {
		t.Fatal(err)
	}
	if timed.Passed || !timed.TimedOut || timed.ExitCode == 0 {
		t.Fatalf("timeout was not reported: %+v", timed)
	}
	if elapsed := time.Since(started); elapsed > 20*time.Second {
		t.Fatalf("timeout did not bound execution: %s", elapsed)
	}
	pid := readPID(t, filepath.Join(slow, "pid.txt"))
	waitProcessGone(t, pid)
}

func TestRunTestCancellationKillsDescendants(t *testing.T) {
	requireSandboxHost(t)
	root := writeSlowNPMProject(t)
	ctx, cancel := context.WithCancel(context.Background())
	go func() {
		for i := 0; i < 200; i++ {
			if _, err := os.Stat(filepath.Join(root, "pid.txt")); err == nil {
				break
			}
			time.Sleep(50 * time.Millisecond)
		}
		cancel()
	}()
	_, err := RunTest(ctx, root, RunTestInput{Toolchain: "npm", TimeoutSeconds: 60})
	if !errors.Is(err, context.Canceled) {
		t.Fatalf("cancel error = %v", err)
	}
	pid := readPID(t, filepath.Join(root, "pid.txt"))
	waitProcessGone(t, pid)
}

