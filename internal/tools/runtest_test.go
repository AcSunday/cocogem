// A released group must not be signaled: once empty, the kernel may recycle the
// PGID and a negative-PID kill would hit an unrelated process group.
func TestTerminateTestGroupSkipsReleasedGroup(t *testing.T) {
	cmd := exec.Command("/usr/bin/true")
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	if err := cmd.Wait(); err != nil {
		t.Fatal(err)
	}
	terminateTestGroup(cmd)
	members, err := proc.GroupMembers(cmd.Process.Pid)
	if err != nil {
		t.Fatal(err)
	}
	if len(members) != 0 {
		t.Fatalf("released process group %d still has members %v", cmd.Process.Pid, members)
	}
}

func TestQueryGoEnvUsesCleanEnvironmentInPrivateDirectory(t *testing.T) {
	dir := t.TempDir()
	report := filepath.Join(dir, "report.txt")
	fake := filepath.Join(dir, "go")
	script := "#!/bin/sh\n{ pwd; env; } > '" + report + "'\nprintf '/fake/goroot\\n/fake/modcache\\n'\n"
	if err := os.WriteFile(fake, []byte(script), 0700); err != nil {
		t.Fatal(err)
	}
	t.Setenv("ANTHROPIC_API_KEY", "secret-test-value")
	t.Setenv("GOFLAGS", "-mod=mod")
	goroot, modcache := queryGoEnv(context.Background(), fake, dir)
	if goroot != "/fake/goroot" || modcache != "/fake/modcache" {
		t.Fatalf("query returned goroot=%q modcache=%q", goroot, modcache)
	}
	raw, err := os.ReadFile(report)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(raw), "ANTHROPIC_API_KEY") || strings.Contains(string(raw), "-mod=mod") {
		t.Fatalf("query inherited the server environment:\n%s", raw)
	}
	resolved, err := filepath.EvalSymlinks(dir)
	if err != nil {
		t.Fatal(err)
	}
	cwd := strings.SplitN(string(raw), "\n", 2)[0]
	if cwd != resolved && cwd != dir {
		t.Fatalf("query ran in %q, want the private query directory %q", cwd, resolved)
	}
	if !strings.Contains(string(raw), "HOME="+filepath.Join(dir, "home")) {
		t.Fatalf("query did not use the private HOME:\n%s", raw)
	}
}

func TestQueryGoEnvIsTimeoutBounded(t *testing.T) {
	dir := t.TempDir()
	fake := filepath.Join(dir, "go")
	if err := os.WriteFile(fake, []byte("#!/bin/sh\nsleep 30\n"), 0700); err != nil {
		t.Fatal(err)
	}
	started := time.Now()
	goroot, modcache := queryGoEnv(context.Background(), fake, dir)
	if goroot != "" || modcache != "" {
		t.Fatalf("timed-out query returned goroot=%q modcache=%q", goroot, modcache)
	}
	if elapsed := time.Since(started); elapsed > 8*time.Second {
		t.Fatalf("query was not bounded by its timeout: %s", elapsed)
	}
}
